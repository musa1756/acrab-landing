export function appLessonOf(letter: Letter): AppLesson | undefined {
  const lesson = COURSE_LESSONS.find((item) => item.chars.includes(letter.char));
  if (!lesson) return undefined;
  return {
    order: ORDINALS_M[lesson.n - 1] ?? "",
    title: lesson.title,
    others: lesson.chars.filter((char) => char !== letter.char).join(" "),
    listening: lesson.listening === true,
  };
}

