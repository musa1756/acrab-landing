export interface Letter {
  slug: string;
  char: string;
  /** Название буквы по-арабски, с огласовками (как в карточке приложения). */
  arabicName: string;
  /** Русское имя, как в таблице на `/arabic-alphabet/`. */
  name: string;
  /** Уточнение, если русское имя совпадает с именем другой буквы. */
  qualifier?: string;
  /** Транскрипция звука, [..]. */
  ipa: string;
  /** Согласный для слогов: «б» → «ба би бу». */
  cons: string;
  /** Звук в одной строке (meta description и блок «Коротко»). */
  soundShort: string;
  /** Вступление страницы. */
  lead: string;
  /** Как образуется звук, с русскими соответствиями. */
  articulation: string;
  /** Типичные ошибки русскоязычных. */
  mistakes: string[];
  /** Как узнать букву на письме. */
  shape: string;
  /** Что происходит с формой при соединении, на примерах. */
  connects: string;
  /** Слово с артиклем: показывает, как читается ال перед этой буквой. */
  article: { ar: string; tr: string; ru: string };
  /** Дополнение к абзацу про артикль. */
  articleExtra?: string;
  words: readonly WordId[];
  /** Пояснения к отдельным словам. */
  wordNotes?: Partial<Record<WordId, string>>;
  /** Пояснение к транскрипции под таблицей слов. */
  trNote?: string;
  lookalikes: LetterLookalike[];
  faq: FaqItem[];
  /** Слоги с огласовками, если они не `буква + фатха/касра/дамма`. */
  syllables?: readonly [string, string, string];
}

