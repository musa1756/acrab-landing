/** Формы буквы с кашидой (ـ), как в карточках приложения. */
export function letterForms(letter: Letter): Record<FormKey, string> {
  const { char } = letter;
  return isConnecting(letter)
    ? { isolated: char, initial: `${char}ـ`, medial: `ـ${char}ـ`, final: `ـ${char}` }
    : { isolated: char, initial: char, medial: `ـ${char}`, final: `ـ${char}` };
}

