const DIACRITICS = /[ً-ٰٟـ]/g;
const HAMZA_CARRIERS = /[أإآٱ]/g;

/** Буквы слова без огласовок; алиф с хамзой и без неё — одна буква. */
export const baseLetters = (arabic: string): string[] => [...arabic.replace(DIACRITICS, "").replace(HAMZA_CARRIERS, "ا")];

export type WordPosition = "в начале" | "в середине" | "в конце";

/** Где в слове стоит буква: «в начале», «в середине», «в конце» (одна буква может быть в нескольких местах). */
export function wordPositions(arabic: string, char: string): WordPosition[] {
  const letters = baseLetters(arabic);
  const positions: WordPosition[] = [];
  if (letters[0] === char) positions.push("в начале");
  if (letters.slice(1, -1).includes(char)) positions.push("в середине");
  if (letters.length > 1 && letters.at(-1) === char) positions.push("в конце");
  return positions;
}

